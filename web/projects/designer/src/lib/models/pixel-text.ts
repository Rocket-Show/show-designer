export const PIXEL_FONT = 'pixel-5x7';
export const PIXEL_FONT_HEIGHT = 7;

// the letters the pixel font has, for the texts which only use them
export function pixelFontHas(letter: string): boolean {
  return pixelFont[letter] !== undefined;
}

// The columns of a letter of the pixel font, each the bits of its seven rows (the top one the lowest bit), as narrow
// as the letter is: the empty columns on both sides left out. A space is three columns wide, a letter the font does
// not have is a question mark.
function letterColumns(letter: string): number[] {
  if (letter === ' ') {
    return [0, 0, 0];
  }

  const rows = pixelFont[letter] || pixelFont['?'];
  const columns: number[] = [];

  for (let column = 0; column < 5; column++) {
    let bits = 0;

    for (let row = 0; row < PIXEL_FONT_HEIGHT; row++) {
      if (rows[row] & (0x10 >> column)) {
        bits |= 1 << row;
      }
    }

    columns.push(bits);
  }

  let first = 0;
  let last = 4;

  while (first < 4 && columns[first] === 0) {
    first++;
  }

  while (last > first && columns[last] === 0) {
    last--;
  }

  return columns.slice(first, last + 1);
}

// A text in the pixel font, a column between two letters: on (255) or off at each pixel, seven rows high
export function pixelFontBitmap(text: string): PixelBitmap {
  const letters = Array.from(text || '');
  const columns: number[] = [];
  const letterStarts: number[] = [];

  letters.forEach((letter, index) => {
    if (index > 0) {
      columns.push(0);
    }

    letterStarts.push(columns.length);
    columns.push(...letterColumns(letter));
  });

  return bitmapOf(columns.length, PIXEL_FONT_HEIGHT, (x, y) => (columns[x] & (1 << y) ? 255 : 0), letterStarts);
}

// A text in a font of the browser (e.g. 'sans-serif'), drawn as many pixels high as passed and either on or off at
// each pixel. None where there is no document to draw it in.
export function browserFontBitmap(text: string, font: string, height: number): PixelBitmap {
  if (typeof document === 'undefined' || !text) {
    return bitmapOf(0, 0, () => 0, []);
  }

  const size = Math.max(4, Math.min(Math.round(height) || 8, 64));
  const canvas = document.createElement('canvas');
  const context = canvas.getContext('2d');
  const fontOf = () => `${size}px ${font}`;
  context.font = fontOf();
  const width = Math.max(1, Math.ceil(context.measureText(text).width));

  // the letters start where the text before them ends
  const letters = Array.from(text);
  const letterStarts = letters.map((letter, index) => Math.round(context.measureText(letters.slice(0, index).join('')).width));

  canvas.width = width;
  canvas.height = size;
  context.font = fontOf();
  context.textBaseline = 'middle';
  context.fillStyle = '#ffffff';
  context.fillText(text, 0, size / 2);

  const pixels = context.getImageData(0, 0, width, size).data;

  return bitmapOf(width, size, (x, y) => (pixels[(y * width + x) * 4 + 3] >= 128 ? 255 : 0), letterStarts);
}

// a bitmap of a brightness for each pixel, of one frame
function bitmapOf(width: number, height: number, valueAt: (x: number, y: number) => number, letterStarts: number[]): PixelBitmap {
  const bytes = new Uint8Array(width * height);

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      bytes[y * width + x] = valueAt(x, y);
    }
  }

  return new PixelBitmap({ width, height, channels: 1, frames: [encodeBase64(bytes)], letterStarts });
}

// the picture of the text of an effect in its font
export function textBitmap(text: string, font: string, height: number): PixelBitmap {
  return font === PIXEL_FONT ? pixelFontBitmap(text) : browserFontBitmap(text, font, height);
}
